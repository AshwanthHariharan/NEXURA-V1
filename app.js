class App {
    constructor() {
        this.languageManager = languageManager;
        this.currentTheme = localStorage.getItem('nexura_theme') || 'light';
        this.populateLanguageDropdown();
        this.setupEventListeners();
        this.loadSavedLanguage();
        this.translatePage();
        this.applyTheme(this.currentTheme);
        this.checkExistingSession();
    }

    populateLanguageDropdown() {
        const select = document.getElementById('languageSelect');
        if (!select) return;

        const languages = this.languageManager.getAvailableLanguages();
        select.innerHTML = '';
        
        languages.forEach(lang => {
            const option = document.createElement('option');
            option.value = lang.code;
            option.textContent = lang.name;
            select.appendChild(option);
        });
    }

    setupEventListeners() {
        // Language change
        const languageSelect = document.getElementById('languageSelect');
        if (languageSelect) {
            languageSelect.addEventListener('change', (e) => {
                const lang = e.target.value;
                this.languageManager.setLanguage(lang);
                this.translatePage();
                console.log('🌐 Language changed to:', lang);
            });
        }

        // Theme toggle
        const themeToggle = document.getElementById('themeToggle');
        if (themeToggle) {
            themeToggle.addEventListener('click', () => {
                const newTheme = this.currentTheme === 'light' ? 'dark' : 'light';
                this.applyTheme(newTheme);
                this.currentTheme = newTheme;
                localStorage.setItem('nexura_theme', newTheme);
                console.log('🎨 Theme changed to:', newTheme);
            });
        }

        // Get Started button
        const getStartedBtn = document.getElementById('getStartedBtn');
        if (getStartedBtn) {
            getStartedBtn.addEventListener('click', (e) => {
                e.preventDefault();
                console.log('🚀 Get Started clicked - redirecting to register...');
                window.location.href = 'register.html';
            });
        }

        // Sign In button
        const signInBtn = document.getElementById('signInBtn');
        if (signInBtn) {
            signInBtn.addEventListener('click', (e) => {
                e.preventDefault();
                console.log('🔐 Sign In clicked - redirecting to login...');
                window.location.href = 'login.html';
            });
        }
        
        this.languageManager.addListener(() => {
            this.translatePage();
        });
    }

    checkExistingSession() {
        const session = localStorage.getItem('nexura_session');
        if (session) {
            try {
                const data = JSON.parse(session);
                const expiry = new Date(data.expiry);
                const now = new Date();
                if (now < expiry) {
                    console.log('✅ Valid session found for:', data.fullName);
                }
            } catch (e) {
                console.log('⚠️ Invalid session found, clearing...');
                localStorage.removeItem('nexura_session');
            }
        }
    }

    loadSavedLanguage() {
        const savedLang = localStorage.getItem('nexura_language') || 'en';
        const select = document.getElementById('languageSelect');
        if (select) {
            select.value = savedLang;
        }
        this.languageManager.setLanguage(savedLang);
    }

    translatePage() {
        this.languageManager.translatePage();
    }

    applyTheme(theme) {
        const themeToggle = document.getElementById('themeToggle');
        if (!themeToggle) return;
        
        const icon = themeToggle.querySelector('i');
        
        if (theme === 'dark') {
            document.documentElement.setAttribute('data-theme', 'dark');
            document.body.classList.add('dark-mode');
            if (icon) {
                icon.className = 'fas fa-sun';
            }
            themeToggle.setAttribute('aria-label', 'Switch to light mode');
        } else {
            document.documentElement.removeAttribute('data-theme');
            document.body.classList.remove('dark-mode');
            if (icon) {
                icon.className = 'fas fa-moon';
            }
            themeToggle.setAttribute('aria-label', 'Switch to dark mode');
        }
    }

    isLoggedIn() {
        const session = localStorage.getItem('nexura_session');
        if (!session) return false;
        try {
            const data = JSON.parse(session);
            const expiry = new Date(data.expiry);
            const now = new Date();
            return now < expiry;
        } catch (e) {
            return false;
        }
    }

    getCurrentUser() {
        const session = localStorage.getItem('nexura_session');
        if (!session) return null;
        try {
            const data = JSON.parse(session);
            const expiry = new Date(data.expiry);
            const now = new Date();
            if (now < expiry) {
                return data;
            }
            return null;
        } catch (e) {
            return null;
        }
    }

    logout() {
        localStorage.removeItem('nexura_session');
        localStorage.removeItem('nexura_current_user');
        console.log('👋 User logged out');
        window.location.href = 'index.html';
    }
}

